/**
 * gamesSlice: the game catalogue, loaded asynchronously from /api/games.
 *
 * Async pattern (createAsyncThunk):
 *   dispatch(fetchGames())
 *     -> "games/fetchGames/pending"    status = "loading"
 *     -> "games/fetchGames/fulfilled"  status = "succeeded", items filled
 *     -> "games/fetchGames/rejected"   status = "failed",    error message
 *
 * Components read `status` to decide what to render:
 *   loading -> skeletons, failed -> error message + retry, succeeded -> data.
 */
import { createAsyncThunk, createSlice } from "@reduxjs/toolkit";
import type { Game } from "@/data/games";
import type { RootState } from "@/store";

export type LoadStatus = "idle" | "loading" | "succeeded" | "failed";

export interface GamesState {
  items: Game[];
  status: LoadStatus;
  error: string | null;
}

const initialState: GamesState = {
  items: [],
  status: "idle",
  error: null,
};

/**
 * Fetch the catalogue.
 * Generic types: <what it returns, its argument, extra config>.
 * `rejectValue: string` lets us send a friendly error message to the reducer.
 */
export const fetchGames = createAsyncThunk<Game[], void, { state: RootState; rejectValue: string }>(
  "games/fetchGames",
  async (_, { rejectWithValue }) => {
    try {
      const response = await fetch("/api/games");
      if (!response.ok) {
        return rejectWithValue(`The server responded with an error (${response.status}).`);
      }
      const data: { games: Game[] } = await response.json();
      return data.games;
    } catch {
      // fetch() itself throws when there's no network at all.
      return rejectWithValue("Couldn't reach the server. Check your connection and try again.");
    }
  },
  {
    // Several components ask for games on mount. `condition` skips the
    // request if one is already in flight or the data is already loaded,
    // so we only ever make one network call.
    condition: (_, { getState }) => {
      const { status } = getState().games;
      return status !== "loading" && status !== "succeeded";
    },
  },
);

const gamesSlice = createSlice({
  name: "games",
  initialState,
  reducers: {},
  // extraReducers respond to actions defined *outside* this slice,
  // here the three lifecycle actions generated by createAsyncThunk.
  extraReducers: (builder) => {
    builder
      .addCase(fetchGames.pending, (state) => {
        state.status = "loading";
        state.error = null;
      })
      .addCase(fetchGames.fulfilled, (state, action) => {
        state.status = "succeeded";
        state.items = action.payload;
      })
      .addCase(fetchGames.rejected, (state, action) => {
        state.status = "failed";
        state.error = action.payload ?? "Something went wrong.";
      });
  },
});

export default gamesSlice.reducer;

// ------------------------------------------------------------- Selectors ---
// Selectors keep "how to find data in the state" in one place, so
// components never depend on the exact shape of the store.

export const selectGamesStatus = (state: RootState) => state.games.status;
export const selectGamesError = (state: RootState) => state.games.error;
export const selectAllGames = (state: RootState) => state.games.items;
